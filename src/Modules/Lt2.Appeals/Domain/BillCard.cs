using NpgsqlTypes;

namespace Lt2.Appeals.Domain;

/// <summary>
/// <c>appeals.bill_card</c>: this module's copy of one bill for searching (design 5.3, 8.12.5): the number, the official title
/// refreshed from the Parliament module after every import, and the readable title written with the record's (design 8.13.1).
/// Public data. Written only by <see cref="Application.BillCards"/> with SQL that computes the folded columns from the same
/// <see cref="Lt2.SharedKernel.SearchText"/> the query's words go through; the database makes the two search columns.
/// </summary>
internal sealed class BillCard
{
    public string BillNumber { get; set; } = "";

    /// <summary>The official title, a copy.</summary>
    public string Title { get; set; } = "";

    /// <summary>The record's readable title, a copy; null while there is none.</summary>
    public string? PlainTitle { get; set; }

    /// <summary>The number and the official title, folded.</summary>
    public string TitleFolded { get; set; } = "";

    /// <summary>The readable title, folded; null while there is none.</summary>
    public string? PlainTitleFolded { get; set; }

    /// <summary>Generated by the database: both folded texts together, for the trigram index.</summary>
    public string SearchFolded { get; private set; } = "";

    /// <summary>Generated by the database: the number and both titles in the <c>lithuanian</c> text search configuration.</summary>
    public NpgsqlTsVector SearchVector { get; private set; } = null!;

    /// <summary>
    /// Generated by the database: the folded texts in the <c>lithuanian</c> configuration, so a word typed without Lithuanian
    /// letters finds its other forms too ("mokesciai" finds "mokesčio": both fold to the stem "mokesc").
    /// </summary>
    public NpgsqlTsVector SearchVectorFolded { get; private set; } = null!;
}
